<?php
declare(strict_types=1);

require_once __DIR__ . '/db.php';
require_once __DIR__ . '/report_helper.php';
require_once __DIR__ . '/../vendor/autoload.php';

use Dompdf\Dompdf;
use Dompdf\Options;

$session = require_role(['admin', 'security']);
$role    = (string) $session['role'];
$userId  = (int) $session['user_id'];

$type     = trim((string) ($_GET['report_type'] ?? 'lost_items'));
$format   = strtolower(trim((string) ($_GET['format'] ?? 'csv')));
$dateFrom = $_GET['date_from'] ?? null;
$dateTo   = $_GET['date_to'] ?? null;
$status   = (string) ($_GET['status'] ?? '');

if ($type === 'audit_trail') {
    require_role(['admin']);
}

if (!in_array($format, ['csv', 'pdf'], true)) {
    json_out(['success' => false, 'message' => 'Invalid export format.'], 400);
}

try {
    $report = fetch_report_data($role, $type, $dateFrom, $dateTo, $status);
} catch (InvalidArgumentException | RuntimeException $e) {
    json_out(['success' => false, 'message' => $e->getMessage()], 403);
}

$generatedAt = date('Y-m-d H:i:s');
$generatedBy = (string) ($session['name'] ?? 'Authorized Staff');
$filterParts = [];
if ($report['date_from']) $filterParts[] = 'From: ' . $report['date_from'];
if ($report['date_to'])   $filterParts[] = 'To: ' . $report['date_to'];
if ($report['status'])    $filterParts[] = 'Status: ' . ucwords(str_replace('_', ' ', $report['status']));
$filterSummary = $filterParts ? implode(' | ', $filterParts) : 'All dates & statuses';

$filenameBase = 'retrieva_' . $report['type'] . '_' . date('Ymd_His');

log_audit($userId, 'report_exported', "type={$report['type']} format={$format} rows=" . count($report['rows']));

if ($format === 'csv') {
    header('Content-Type: text/csv; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filenameBase . '.csv"');
    header('X-Content-Type-Options: nosniff');

    $out = fopen('php://output', 'wb');
    fwrite($out, "\xEF\xBB\xBF");
    fputcsv($out, [csv_safe_cell($report['title'])]);
    fputcsv($out, ['Generated At', csv_safe_cell($generatedAt), 'Generated By', csv_safe_cell($generatedBy)]);
    fputcsv($out, ['Applied Filters', csv_safe_cell($filterSummary), 'Total Records', (string) count($report['rows'])]);
    fputcsv($out, []);
    fputcsv($out, array_map('csv_safe_cell', $report['columns']));
    foreach ($report['rows'] as $row) {
        fputcsv($out, array_map('csv_safe_cell', $row));
    }
    fclose($out);
    exit;
}

if (!class_exists(Dompdf::class)) {
    json_out(['success' => false, 'message' => 'PDF library (Dompdf) is not installed.'], 500);
}

$thHtml = '';
foreach ($report['columns'] as $col) {
    $thHtml .= '<th>' . h($col) . '</th>';
}

$rowsHtml = '';
if (!$report['rows']) {
    $colspan = count($report['columns']);
    $rowsHtml = '<tr><td colspan="' . $colspan . '" class="empty">No records match the selected filters.</td></tr>';
} else {
    foreach ($report['rows'] as $row) {
        $rowsHtml .= '<tr>';
        foreach ($row as $cell) {
            $rowsHtml .= '<td>' . h((string) $cell) . '</td>';
        }
        $rowsHtml .= '</tr>';
    }
}

$html = '<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<style>
  body { font-family: DejaVu Sans, sans-serif; font-size: 10.5px; color: #1F2A3D; margin: 20px; }
  .header { border-bottom: 3px solid #003276; padding-bottom: 10px; margin-bottom: 14px; }
  .brand { font-size: 10px; font-weight: bold; color: #F5A623; letter-spacing: 1px; text-transform: uppercase; }
  h1 { margin: 3px 0 4px; font-size: 18px; color: #003276; }
  .meta { font-size: 9.5px; color: #6B7686; line-height: 1.5; }
  table { width: 100%; border-collapse: collapse; margin-top: 10px; }
  th { background: #003276; color: #FFFFFF; text-align: left; padding: 7px 6px; font-size: 9px; text-transform: uppercase; }
  td { border-bottom: 1px solid #E6E9F0; padding: 6px; vertical-align: top; word-wrap: break-word; }
  tr:nth-child(even) td { background: #FAFBFD; }
  .empty { text-align: center; padding: 20px; color: #6B7686; }
  .footer { margin-top: 16px; font-size: 8.5px; color: #6B7686; text-align: right; }
</style>
</head>
<body>
  <div class="header">
    <div class="brand">Retrieva — University of Makati Lost &amp; Found</div>
    <h1>' . h($report['title']) . '</h1>
    <div class="meta">
      <strong>Generated:</strong> ' . h($generatedAt) . ' &nbsp;|&nbsp;
      <strong>By:</strong> ' . h($generatedBy) . '<br>
      <strong>Filters:</strong> ' . h($filterSummary) . ' &nbsp;|&nbsp;
      <strong>Total Records:</strong> ' . count($report['rows']) . '
    </div>
  </div>
  <table>
    <thead><tr>' . $thHtml . '</tr></thead>
    <tbody>' . $rowsHtml . '</tbody>
  </table>
  <div class="footer">Confidential — Generated via Retrieva Reporting Module</div>
</body>
</html>';

$options = new Options();
$options->set('isHtml5ParserEnabled', true);
$options->set('isRemoteEnabled', false);

$dompdf = new Dompdf($options);
$dompdf->loadHtml($html);
$dompdf->setPaper('A4', $type === 'inventory' ? 'portrait' : 'landscape');
$dompdf->render();
$dompdf->stream($filenameBase . '.pdf', ['Attachment' => true]);
exit;
