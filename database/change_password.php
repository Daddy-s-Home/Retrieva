<?php
declare(strict_types=1);
require_once __DIR__ . '/db.php';
$session = require_login();
header('Content-Type: application/json');
$input = json_decode(file_get_contents('php://input'), true) ?? [];
$current = (string)($input['current_password'] ?? '');
$password = (string)($input['password'] ?? '');
$confirm = (string)($input['confirm_password'] ?? '');
if ($current === '' || $password === '' || $confirm === '') json_out(['success' => false, 'message' => 'All password fields are required.'], 400);
if (strlen($password) < 8) json_out(['success' => false, 'message' => 'Password must be at least 8 characters.'], 400);
if ($password !== $confirm) json_out(['success' => false, 'message' => 'Passwords do not match.'], 400);
$stmt = get_db()->prepare('SELECT password_hash FROM users WHERE id = ?');
$stmt->execute([$session['user_id']]);
$user = $stmt->fetch();
if (!$user || !$user['password_hash'] || !password_verify($current, $user['password_hash'])) json_out(['success' => false, 'message' => 'Current password is incorrect.'], 401);
$update = get_db()->prepare('UPDATE users SET password_hash = ?, password_is_set = 1, auth_provider = "local" WHERE id = ?');
$update->execute([password_hash($password, PASSWORD_BCRYPT), $session['user_id']]);
log_audit((int)$session['user_id'], 'password_changed', 'Password changed from account settings.');
json_out(['success' => true, 'message' => 'Password updated.']);
